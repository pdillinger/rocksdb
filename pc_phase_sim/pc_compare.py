# TEMPORARY (not for commit). Side-by-side comparison of pc_phase_sim runs
# against TriggerTime variants. Expects <out_dir>/<variant>/<scenario>.csv
# (one pc_phase_sim process per (variant, scenario); see run_all.sh). Badness
# is computed with compute_badness from pc_phase_gen.py (the analyzer behind
# the original pc_phase_sim.html) so numbers are comparable with that page.
# Adds:
#   peak load  = max periodic compactions per DB per period P, in P/40 bins
#                aligned at the change (or at 0 when there is no change)
#   early load = periodic compactions per DB per P over [change, change+0.1P)
# Writes <html_out> (plot page in the pc_phase_sim style) and prints a
# markdown table. The template supplies the page's CSS and SVG plot function;
# either the original pc_phase_sim.html or a page generated by this script
# works.
#
# Usage: python3 pc_compare.py out_dir template.html html_out [finding.html]

import csv
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pc_phase_gen as gen  # noqa: E402

VARIANTS = [
    ("current", "current code"),
    ("kmax", "k = max(q, 1/2)"),
    ("khalf", "k = 1/2 (chosen)"),
]
NOISE = ("current_rep", "current (replicate)")

# (name, run length in N, change time in N or None, period in N)
SCENARIOS = [
    ("upgrade_dynamic_r33", 8.0, 2.4, 1),
    ("upgrade_dynamic_r50", 8.0, 2.4, 1),
    ("upgrade_dynamic_r100", 8.0, 2.4, 1),
    ("upgrade_restart_r33", 8.0, 2.4, 1),
    ("midlife_dynamic_r33", 8.0, 2.4, 1),
    ("midlife_dynamic_r50", 8.0, 2.4, 1),
    ("midlife_dynamic_r100", 8.0, 2.4, 1),
    ("staggered_phased_r33", 6.2, None, 1),
    ("turndown_r33", 9.0, 3.5, 1),
    ("turnup_r33", 12.0, 2.0, 3),
    ("natural_sync_r0", 5.2, None, 1),
    ("natural_sync_r33", 6.2, None, 1),
    ("natural_sync_r50", 6.2, None, 1),
    ("natural_stag_r33", 6.2, None, 1),
    ("burst_r0", 5.2, None, 1),
    ("burst_r25", 6.2, None, 1),
    ("burst_r33", 6.2, None, 1),
    ("burst_r50", 6.2, None, 1),
    ("burst_r100", 6.2, None, 1),
]

DESC = dict(gen.DESC)
for q in (33, 50, 100):
    DESC["midlife_dynamic_r%d" % q] = (
        "NEW. Pure periodic, interval N, staggered fresh times (file ages "
        "uniform over a period), phasing OFF until a dynamic SetDBOptions "
        "enable to rp=%d%% at t=2.4N -- the production switchover case. With "
        "the current code, DBs whose recovery target "
        "falls before the anchor are spread uniformly over [anchor, deadline], "
        "which front-loads triggers just after the enable." % q
    )

LOAD_BINS = 40  # per period
FINE_BINS = 100  # per period, for the post-change window
FINE_PRE, FINE_POST = 0.1, 0.5  # fine window around the change, in periods
SCATTER_DBS = 40  # DBs shown in the timeline scatter
REGRESSION = 0.05


def read_events(path):
    ev, M, N = [], None, None
    with open(path) as f:
        for r in csv.DictReader(f):
            ev.append((float(r["t_rel_s"]), int(r["db"]), r["kind"]))
            M, N = int(r["M"]), int(r["N"])
    return ev, M, N


def analyze(name, events, N, M, run_mult, change_mult, pmult):
    tmax = run_mult * N
    P = pmult * N
    change = change_mult * N if change_mult is not None else None
    hold = change if (change is not None and name in gen.HOLD_BADNESS) else 0.0
    b = gen.compute_badness(events, P, tmax, start=hold)
    per = [t for t, _, k in events if k == "P"]
    # Load per DB per period, in P/40 bins over the whole run (for plotting).
    lw = P / LOAD_BINS
    nb = int(math.ceil(tmax / lw))
    load = [0.0] * nb
    for t in per:
        i = int(t // lw)
        if 0 <= i < nb:
            load[i] += 1
    load = [x * LOAD_BINS / M for x in load]
    # Peak load: bins aligned at the change (or 0), full bins only.
    c0 = change if change is not None else 0.0
    npk = int((tmax - c0) // lw)
    pk = [0] * npk
    for t in per:
        i = int((t - c0) // lw)
        if 0 <= i < npk:
            pk[i] += 1
    peak_load = max(pk) * LOAD_BINS / M if pk else 0.0
    early = None
    fine = None
    if change is not None:
        early = sum(1 for t in per if change <= t < change + 0.1 * P) * 10.0 / M
        fw = P / FINE_BINS
        f0 = change - FINE_PRE * P
        nf = int(round((FINE_PRE + FINE_POST) * FINE_BINS))
        fine = [0] * nf
        for t in per:
            i = int(math.floor((t - f0) / fw))
            if 0 <= i < nf:
                fine[i] += 1
        fine = [round(x * FINE_BINS / M, 3) for x in fine]
    # An evenly spaced sample of DBs (row i = DB i * stride). In staggered
    # scenarios DB index follows seed time, so a prefix of DBs would all be
    # seeded within a sliver of the period and falsely look like a herd.
    stride = max(1, M // SCATTER_DBS)
    scatter = [
        [round(t, 1), db // stride, 1 if k == "P" else 0]
        for t, db, k in events
        if db % stride == 0 and db // stride < SCATTER_DBS
    ]
    return {
        "peak_load": round(peak_load, 3),
        "early_load": None if early is None else round(early, 3),
        "peak_inst": b["peak_inst"],
        "steady_inst": b["steady_inst"],
        "end_cum": b["end_cum"],
        "nP": len(per),
        "nW": sum(1 for _, _, k in events if k == "W"),
        "badness_t": b["badness_t"],
        "badness_inst": b["badness_inst"],
        "badness_cum": b["badness_cum"],
        "load_w": lw,
        "load": [round(x, 3) for x in load],
        "fine_t0": None if change is None else round(change - FINE_PRE * P, 3),
        "fine_w": P / FINE_BINS,
        "fine": fine,
        "events": scatter,
    }


def pct(new, old):
    if old == 0:
        return 0.0 if new == 0 else math.inf
    return (new - old) / old


def main():
    out_dir, template, html_out = sys.argv[1], sys.argv[2], sys.argv[3]
    variants = VARIANTS + ([NOISE] if os.path.isdir(os.path.join(out_dir, NOISE[0])) else [])
    data = {"variants": [[v, label] for v, label in variants], "scenarios": []}
    N = M = None
    for name, run_mult, change_mult, pmult in SCENARIOS:
        sc = {
            "name": name,
            "gridN": None,
            "upgrade_t": None,
            "x0": 0.0,
            "tmax": None,
            "res": {},
        }
        for v, _ in variants:
            path = os.path.join(out_dir, v, name + ".csv")
            if not os.path.exists(path):
                continue
            ev, m, n = read_events(path)
            if not ev:
                continue
            M, N = m, n
            sc["res"][v] = analyze(name, ev, n, m, run_mult, change_mult, pmult)
            sc["gridN"] = pmult * n
            sc["upgrade_t"] = None if change_mult is None else change_mult * n
            sc["x0"] = gen.X0_MULT.get(name, 0.0) * n
            sc["tmax"] = run_mult * n
        if sc["res"]:
            data["scenarios"].append(sc)
    data["N"], data["M"], data["scatter_dbs"] = N, M, SCATTER_DBS
    data["scatter_stride"] = max(1, M // SCATTER_DBS)
    if len(sys.argv) > 4:
        data["finding"] = open(sys.argv[4]).read()

    # Regression flags vs current (peak load, steady badness), plus the
    # current-vs-replicate difference as a noise reference.
    rows = []
    for sc in data["scenarios"]:
        cur = sc["res"].get("current")
        flags = {}
        for v, _ in VARIANTS[1:]:
            r = sc["res"].get(v)
            if cur is None or r is None:
                continue
            f = []
            if pct(r["peak_load"], cur["peak_load"]) > REGRESSION:
                f.append("peak load")
            if pct(r["steady_inst"], cur["steady_inst"]) > REGRESSION and (
                r["steady_inst"] - cur["steady_inst"] > 0.0005
            ):
                f.append("steady badness")
            flags[v] = f
        sc["flags"] = flags
        rows.append(sc)

    # Markdown table to stdout.
    def cell(sc, v, key, fmt):
        r = sc["res"].get(v)
        if r is None or r[key] is None:
            return "-"
        return fmt % r[key]

    vs = [v for v, _ in variants]
    print("N=%s M=%s (one process per scenario x variant; paired phases)\n" % (N, M))
    print(
        "| scenario | peak load (" + " / ".join(vs) + ") | early load 0.1N ("
        + " / ".join(vs) + ") | badness peak | badness steady | badness end | flags |"
    )
    print("|---|---|---|---|---|---|---|")
    for sc in rows:
        def grp(key, fmt):
            return " / ".join(cell(sc, v, key, fmt) for v in vs)

        fl = "; ".join(
            "%s: %s" % (v, ", ".join(f)) for v, f in sc["flags"].items() if f
        )
        print(
            "| %s | %s | %s | %s | %s | %s | %s |"
            % (
                sc["name"],
                grp("peak_load", "%.2f"),
                grp("early_load", "%.2f"),
                grp("peak_inst", "%.2f"),
                grp("steady_inst", "%.3f"),
                grp("end_cum", "%.3f"),
                fl or "",
            )
        )

    html = open(template).read()
    head = html[: html.index("<body>") + len("<body>")]
    head = head.replace(
        "<title>Periodic Compaction Preferred-Phase: Badness</title>",
        "<title>Periodic compaction phase: post-anchor catch-up variants</title>",
    )
    a = html.index("function plot(el,c){")
    b = html.index("\n}\n", a) + len("\n}\n")
    plot_js = html[a:b] + "\n"
    page = head + BODY % {"N": N, "M": M}
    page += "<script>\nconst DATA=" + json.dumps(data, separators=(",", ":")) + ";\n"
    page += "const DESC=" + json.dumps(DESC) + ";\n"
    page += plot_js + PAGE_JS + "</script></body></html>\n"
    open(html_out, "w").write(page)
    print("\nWrote %s (%d bytes)" % (html_out, len(page)))


